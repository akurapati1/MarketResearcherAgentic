import { useQuery } from "@tanstack/react-query";
import { Check, KeyRound } from "lucide-react";
import { useState } from "react";
import { Card, PageHeader } from "../components/ui";
import { api, apiKey } from "../lib/api";

export default function SettingsPage() {
  const { data: cfg } = useQuery({ queryKey: ["config"], queryFn: api.config });
  const [key, setKey] = useState(apiKey.get());
  const [saved, setSaved] = useState(false);
  const rows: [string, string][] = cfg ? [
    ["LLM provider", cfg.llm.enabled ? cfg.llm.provider : "Not configured — using built-in heuristic engine"],
    ["Market data mode", cfg.market_data_mode], ["Concurrent job workers", String(cfg.max_concurrent_jobs)], ["API auth", cfg.auth_required ? "Required" : "Open"],
  ] : [];
  return (
    <div className="max-w-2xl">
      <PageHeader title="Settings" sub="Runtime configuration is set on the server via environment variables." />
      <Card className="mb-6">
        <dl className="divide-y divide-white/5">{rows.map(([k, v]) => <div key={k} className="flex justify-between gap-4 py-3 text-sm"><dt className="text-slate-400">{k}</dt><dd className="text-right font-medium text-white">{v}</dd></div>)}</dl>
        {!cfg?.llm.enabled && <p className="mt-3 rounded-lg bg-brand/10 p-3 text-xs text-indigo-200">Set <code className="mono">ANTHROPIC_API_KEY</code> on the backend to enable LLM-written analysis. Without it, reports are generated by the deterministic rule engine.</p>}
      </Card>
      <Card>
        <p className="mb-3 flex items-center gap-2 text-sm font-semibold text-white"><KeyRound size={16} className="text-cyan" /> API key</p>
        <p className="mb-3 text-xs text-slate-400">Only needed if the server sets <code className="mono">API_KEY</code>. Stored in this browser only.</p>
        <div className="flex gap-2">
          <input type="password" className="input" value={key} onChange={(e) => { setKey(e.target.value); setSaved(false); }} placeholder="X-API-Key" />
          <button className="btn-primary" onClick={() => { apiKey.set(key); setSaved(true); }}>{saved ? <Check size={16} /> : "Save"}</button>
        </div>
      </Card>
    </div>
  );
}
