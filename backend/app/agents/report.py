"""Assemble the final report document (JSON + markdown) from the agent context."""
from __future__ import annotations

from datetime import datetime, timezone

from ..data.indicators import sma
from .analyst import news_sentiment, score_instrument, stance_for
from .context import ResearchContext

DISCLAIMER = ("This report is generated by automated agents for informational and research purposes only. "
              "It is not investment advice. Verify all data independently before making decisions.")


def _series(bars: list[dict]) -> list[dict]:
    closes = [b["c"] for b in bars]
    s20, s50 = sma(closes, 20), sma(closes, 50)
    step = max(1, len(bars) // 260)
    out = []
    for i in range(0, len(bars), step):
        out.append({"t": bars[i]["t"], "c": bars[i]["c"],
                    "sma20": round(s20[i], 2) if s20[i] else None,
                    "sma50": round(s50[i], 2) if s50[i] else None,
                    "v": bars[i]["v"]})
    if out[-1]["t"] != bars[-1]["t"]:
        out.append({"t": bars[-1]["t"], "c": bars[-1]["c"], "sma20": None, "sma50": None, "v": bars[-1]["v"]})
    return out


def build_markdown(r: dict) -> str:
    a = r["recommendation"]
    lines = [f"# {r['title']}", "",
             f"_Generated {r['generated_at']} · engine: {r['engine']} · depth: {r['depth']}_", "",
             "## Executive Summary", r["executive_summary"], "",
             f"**Stance:** {a['stance']} · **Confidence:** {a['confidence']}% · **Horizon:** {a['horizon']}", "",
             "## Key Findings", *[f"- {f}" for f in r["key_findings"]], ""]
    for s in r["sections"]:
        lines += [f"## {s['heading']}", s["body"], ""]
    sw = r["swot"]
    lines.append("## SWOT")
    for label, key in (("Strengths", "strengths"), ("Weaknesses", "weaknesses"),
                       ("Opportunities", "opportunities"), ("Threats", "threats")):
        lines += [f"**{label}**", *[f"- {x}" for x in sw[key]], ""]
    if r["review_notes"]:
        lines += ["## Reviewer Notes", *[f"- {n}" for n in r["review_notes"]], ""]
    if r["news"]:
        lines += ["## Sources", *[f"- [{n['title']}]({n['url']}) — {n['source']}" for n in r["news"] if n["url"]], ""]
    lines += ["---", f"_{r['disclaimer']}_"]
    return "\n".join(lines)


def build_report(ctx: ResearchContext, job_id: str, scores_meta: dict) -> dict:
    a, sent = ctx.analysis, scores_meta["sentiment"]
    instruments = []
    for sym, snap in ctx.snapshots.items():
        sc, _ = score_instrument(snap["indicators"], sent["score"])
        instruments.append({
            "symbol": sym, "name": snap["quote"]["name"], "quote": snap["quote"],
            "indicators": snap["indicators"], "score": round(sc, 3), "stance": stance_for(sc),
            "series": _series(snap["bars"]),
        })
    report = {
        "job_id": job_id, "title": ctx.plan.title or ctx.query[:100], "query": ctx.query, "depth": ctx.depth,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "engine": " + ".join(sorted(ctx.engine_used - {"heuristic"})) + (
            " (+heuristics)" if "heuristic" in ctx.engine_used and len(ctx.engine_used) > 1 else "")
        if ctx.engine_used - {"heuristic"} else "heuristic rule engine",
        "data_quality": "synthetic" if ctx.synthetic else "live",
        "executive_summary": a.executive_summary, "key_findings": a.key_findings,
        "swot": a.swot.model_dump(), "risks": [r.model_dump() for r in a.risks],
        "recommendation": a.recommendation.model_dump(),
        "sentiment": news_sentiment(ctx.news), "news": ctx.news,
        "instruments": instruments, "sections": ctx.sections, "questions": ctx.plan.questions,
        "review_notes": ctx.review_notes, "disclaimer": DISCLAIMER,
    }
    report["markdown"] = build_markdown(report)
    return report
